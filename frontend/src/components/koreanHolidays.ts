/** 서버(Google 공휴일 캘린더) 목록을 내장 목록 위에 덮어써서, 같은 날짜는 서버 이름을 쓴다. */
export function mergeHolidays(fetched: Holiday[] | undefined): HolidayMap {
  const merged = { ...BUILT_IN_HOLIDAYS }
  for (const holiday of fetched ?? []) merged[holiday.date] = holiday.name
  return merged
}

export function holidayName(day: Date, holidays: HolidayMap = BUILT_IN_HOLIDAYS): string | null {
  return holidays[dateKey(day)] ?? null
}

/** 일요일·공휴일·대체공휴일은 빨간색(holiday), 토요일은 파란색(saturday)으로 표시한다. */
export function dayTone(day: Date, holidays: HolidayMap = BUILT_IN_HOLIDAYS): 'holiday' | 'saturday' | null {
  if (day.getDay() === 0 || holidayName(day, holidays)) return 'holiday'
  if (day.getDay() === 6) return 'saturday'
  return null
}
